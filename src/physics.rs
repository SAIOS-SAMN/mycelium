/// Per-lane kinematic pressure, torsion, and the SYNTROPIC/ENTROPIC metabolism.
/// Arrays, never a summed scalar (#34). The metabolism is the governing physics
/// of the hypha↔client exchange: syntropic events (settlements — order built,
/// negentropy) and entropic events (pivots/backlog — disorder) net per lane into
/// the order flux that paces serving and demand cadence.
/// The metabolic reserve's ceiling — full at rest.
pub const RESERVE_MAX: u64 = 32;
/// Reserve spent by one entropic expansion (a germination) on a lane.
const SPEND: u64 = 4;
/// Reserve regenerated by one syntropic optimization (a consolidation) step.
/// Deliberately BELOW one expansion's spend: a depleted lane needs two strokes per
/// install, so sustained germination runs at the regeneration pace (homeostasis)
/// and bursts genuinely defer — the two-stroke is a governor, not a formality.
const REGEN: u64 = 2;
/// The floor below which a lane is DEPLETED — the mesh enters the syntropic phase.
const EXPAND_MIN: u64 = 4;

#[derive(Debug, Clone, PartialEq, Eq)]
